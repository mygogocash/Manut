function buildAllCountries(): string[] {
  try {
    const display = new Intl.DisplayNames(["en"], { type: "region" });
    const names = ISO_3166_ALPHA2.map((code) => display.of(code)).filter(
      (name): name is string => !!name,
    );
    return Array.from(new Set(names)).sort((a, b) => a.localeCompare(b));
  } catch {
    return [...CRM_COMMON_COUNTRIES];
  }
}

/** Full ISO-3166 country list for the account country dropdown.
 *  Computed once at module load via Intl.DisplayNames. */
export const CRM_ALL_COUNTRIES: readonly string[] = buildAllCountries();
