/**
 * Pre-bundle the Express API for the Next.js pages bridge on Vercel.
 *
 * Next/webpack rejects `require(variable)` ("expression is too dynamic") and
 * cannot compile apps/api `@/*` aliases. This script emits a CJS file under
 * apps/web that the bridge can require with a static path.
 */
import { existsSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const nodeRequire = createRequire(import.meta.url);

function loadEsbuild() {
  // tsx (apps/api) depends on esbuild; the pnpm override pins 0.28.1.
  const candidates = [
    path.join(root, "apps/api/node_modules/tsx/package.json"),
    path.join(root, "node_modules/tsx/package.json"),
    path.join(root, "node_modules/.pnpm/esbuild@0.28.1/node_modules/esbuild/package.json"),
  ];
  for (const pkg of candidates) {
    if (!existsSync(pkg)) continue;
    try {
      return createRequire(pkg)("esbuild");
    } catch {
      /* try next */
    }
  }
  return nodeRequire("esbuild");
}

const esbuild = loadEsbuild();

const apiSrc = path.join(root, "apps/api/src");
const outfile = path.join(root, "apps/web/src/server/vercel-api.cjs");

function resolveAtAlias(rel) {
  const base = path.join(apiSrc, rel);
  for (const ext of [".ts", ".js", ".tsx", ".json"]) {
    const candidate = base + ext;
    if (existsSync(candidate)) return candidate;
  }
  for (const idx of ["index.ts", "index.js"]) {
    const candidate = path.join(base, idx);
    if (existsSync(candidate)) return candidate;
  }
  return `${base}.ts`;
}

await esbuild.build({
  entryPoints: [path.join(apiSrc, "vercel-entry.ts")],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  outfile,
  logLevel: "info",
  packages: "bundle",
  // Native addons only — Prisma client JS is bundled; engines are copied beside the outfile.
  external: [
    "sharp",
    "fsevents",
    "canvas",
    "bufferutil",
    "utf-8-validate",
  ],
  plugins: [
    {
      name: "api-at-alias",
      setup(build) {
        build.onResolve({ filter: /^@\// }, (args) => ({
          path: resolveAtAlias(args.path.slice(2)),
        }));
      },
    },
  ],
  banner: {
    js: "/* Generated by scripts/bundle-api-for-vercel.mjs — do not edit */\n",
  },
});

console.log(`Wrote ${path.relative(root, outfile)}`);

// Prisma looks for engines next to the bundle (__dirname) and at
// cwd/src/generated/prisma (path baked into the generated client).
const { copyFileSync, mkdirSync, readdirSync } = await import("node:fs");
const prismaDir = path.join(root, "packages/database/src/generated/prisma");
const outDir = path.dirname(outfile);
const cwdFallbackDir = path.join(root, "apps/web/src/generated/prisma");
const onVercel = Boolean(process.env.VERCEL);

function shouldCopyEngine(name) {
  if (name.endsWith(".wasm")) return true;
  if (!name.endsWith(".node")) return false;
  // Vercel Fluid runs on RHEL — one engine keeps deploy size ~17MB smaller.
  if (onVercel) return name.includes("rhel-openssl-3.0.x");
  if (name.includes("rhel-openssl-3.0.x") || name.includes("debian-openssl-3.0.x")) {
    return true;
  }
  // Local smoke-test on macOS.
  return name.includes("darwin");
}

if (existsSync(prismaDir)) {
  mkdirSync(cwdFallbackDir, { recursive: true });
  for (const name of readdirSync(prismaDir)) {
    if (!shouldCopyEngine(name)) continue;
    for (const destDir of [outDir, cwdFallbackDir]) {
      copyFileSync(path.join(prismaDir, name), path.join(destDir, name));
    }
    console.log(`Copied engine ${name}`);
  }
}
