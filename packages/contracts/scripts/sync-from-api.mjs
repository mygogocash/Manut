// Copies the request/response contracts out of the legacy Express API into
// this package and rewrites their imports. Legacy apps/api keeps its own copies
// until Phase 9 deletes it; re-run this after any change to a *.validation.ts
// there so both stacks validate identically.
//
// Rules:
//   @/common/constants/permissions            -> src/common/constants/permissions.ts
//   @/common/optional-ymd-range                -> src/common/optional-ymd-range.ts
//   @/modules/expenses/expense-shared          -> src/common/date-parts.ts (datePartsInTimezone only)
//   @/modules/accounting/gl-posting.service    -> src/modules/accounting/gl-posting.constants.ts
//   @/modules/<m>/<file>                       -> src/modules/<m>/<file>.ts (copied when listed below)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { resolve, dirname, relative, join } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const apiSrc = join(root, "apps/api/src");
const outSrc = join(root, "packages/contracts/src");

const walk = (dir, acc = []) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (name.endsWith(".validation.ts")) acc.push(p);
  }
  return acc;
};

// Non-validation files the schemas depend on (pure constants/types only).
const CLOSURE = [
  "common/constants/permissions.ts",
  "common/optional-ymd-range.ts",
  "modules/opportunities/opportunities.constants.ts",
  "modules/hrms/attendance-timezone.util.ts",
  "modules/hrms/attendance.types.ts",
  "modules/projects/workflow/workflow.types.ts",
  "modules/investors/investor-pipeline.ts",
  "modules/approval-chains/chain.types.ts",
  "modules/crm-shared/bulk-validation.ts",
  "modules/projects/project-task-priority.ts",
  "modules/proposals/proposal.types.ts",
];

const REMAP = {
  "@/modules/expenses/expense-shared": "common/date-parts",
  "@/modules/accounting/gl-posting.service": "modules/accounting/gl-posting.constants",
};

const files = [...walk(join(apiSrc, "modules")).map((p) => relative(apiSrc, p)), ...CLOSURE];
let count = 0;
for (const rel of files) {
  const from = join(apiSrc, rel);
  const to = join(outSrc, rel);
  let code = readFileSync(from, "utf8");
  code = code.replace(/from "@\/([^"]+)"/g, (_m, spec) => {
    const alias = `@/${spec}`;
    const target = REMAP[alias] ?? spec;
    let relPath = relative(dirname(rel), target).replace(/\\/g, "/");
    if (!relPath.startsWith(".")) relPath = `./${relPath}`;
    return `from "${relPath}"`;
  });
  mkdirSync(dirname(to), { recursive: true });
  writeFileSync(to, code);
  count++;
}

// Barrel: one namespace per module so callers get `contracts.leave.createLeaveSchema`.
const modules = files
  .filter((f) => f.endsWith(".validation.ts"))
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();
const ident = (p) => p.split("/").slice(1).join("_").replace(/\.validation$/, "").replace(/[^A-Za-z0-9_]/g, "_").replace(/^(\d)/, "_$1");
const barrel = [
  "// GENERATED by scripts/sync-from-api.mjs — do not edit.",
  ...modules.map((m) => `export * as ${ident(m)} from "./${m}";`),
  'export * from "./common/constants/permissions";',
  "",
].join("\n");
writeFileSync(join(outSrc, "index.ts"), barrel);
console.log(`sync-from-api: copied ${count} files, ${modules.length} schema modules`);
